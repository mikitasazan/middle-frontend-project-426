// Мониторинг ошибок бэкенда. Заглушка: SDK стоит в зависимостях, но без DSN не включается,
// и приложение работает так, будто мониторинга нет.
//
// Вендор не фиксирован. SDK — Sentry, потому что его протокол понимают и Sentry, и совместимые
// с ним сборщики (например, самохостимый Bugsink): подключение сводится к одной переменной
// окружения, код не меняется. Чеклист требует не вендора, а результат — чтобы неперехваченные
// ошибки с прода были видны во внешнем сервисе.
//
// Воркфлоу подключения — docs/monitoring.md.

import * as Sentry from "@sentry/node";

let enabled = false;

export const initMonitoring = (): void => {
  const dsn = process.env.MONITORING_DSN;
  if (!dsn) {
    // Не молчим: иначе «мониторинг не работает» выясняется в момент, когда он нужен.
    console.log("Мониторинг ошибок выключен: MONITORING_DSN не задан.");
    return;
  }

  Sentry.init({
    dsn,
    environment: process.env.NODE_ENV ?? "development",
    // Трейсинг производительности проекту не нужен: собираем только ошибки.
    tracesSampleRate: 0,
  });
  enabled = true;
};

// Отправлять стоит только непредвиденные ошибки. Бизнес-отказы (занятый email, недоступный
// товар) — штатный результат работы приложения, и в дашборде они превратились бы в шум,
// в котором настоящая поломка не видна.
export const captureError = (error: unknown): void => {
  if (!enabled) {
    return;
  }
  Sentry.captureException(error);
};
