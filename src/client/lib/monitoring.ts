// Мониторинг ошибок фронтенда. Заглушка того же вида, что на сервере: без DSN не включается.
//
// SDK подгружается динамическим импортом, а не статическим: без DSN он не попадает в основной
// бандл и не тянет вес на каждую загрузку страницы. Появится переменная — появится и загрузка.
//
// Адрес сборщика приходит в бандл на этапе сборки, а не в рантайме: Vite подставляет только
// переменные с префиксом VITE_ и делает это при сборке. Отсюда разница с DATABASE_URL — почему
// так и что делать, если понадобится конфигурация без пересборки, написано в docs/monitoring.md.

const dsn = import.meta.env.VITE_MONITORING_DSN;

export const initMonitoring = async (): Promise<void> => {
  if (!dsn) {
    console.log("Мониторинг ошибок выключен: VITE_MONITORING_DSN не задан.");
    return;
  }

  const Sentry = await import("@sentry/react");
  Sentry.init({
    dsn,
    environment: import.meta.env.MODE,
    // Собираем ошибки, а не производительность: трейсинг проекту не нужен.
    tracesSampleRate: 0,
  });
};
